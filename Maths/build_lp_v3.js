    if (rep > 0) {
      _cutStrip(slide, MARGIN, repTop, SLIDE_W - 2 * MARGIN);
    }

    // ── LL — one per rep (LP1 adapted only) ──────────────────────────────
    if (isTypeA) injectLabel(slide, lblX, contentTop);

