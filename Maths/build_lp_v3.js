function _cutStrip(slide, x, y, w) {
  slide.addShape("line", {
    x, y, w, h: 0,
    line: { color: "BBBBBB", width: 0.5, dashType: "lgDash" }
  });
  slide.addText("✂", {
    x: x - 0.16, y: y - 0.09, w: 0.16, h: 0.16,
    fontSize: 9, fontFace: FONT_M, color: "AAAAAA", margin: 0
  });
}

// Strip "Work out" / "Calculate" prefix from calculation questions
function _calcText(n, raw) {
  const q = raw.replace(/^Work out\s+/i, "").replace(/^Calculate\s+/i, "");
  return `Q${n})   ${q} =`;
}

// ── LP1 ARITHMETIC — FULL PAGE ───────────────────────────────────────────────
// Auto-detects short calculations vs word problems by question length.
function buildLP1Arithmetic(slide, isMarkingStation) {
  // compact flag takes priority — short fraction/calculation questions
  // are ≤50 chars and would otherwise fall through to the 10-strip grid
  // layout which ignores compact entirely.
  if (LP1_DATA.compact) {
    _buildCompactWithData(slide, isMarkingStation, LP1_DATA);
    return;
  }
  const questions  = LP1_DATA.questions;
  const maxQLen    = Math.max(...questions.map(q => q.q.length));
  const isWordProb = maxQLen > 50;   // word problems need vertical layout

  if (isWordProb) {
    _buildLP1WordProblems(slide, isMarkingStation);
  } else {
    _buildLP1Calculations(slide, isMarkingStation);
  }
}

// Short calculations: 10-strip, 2-column grid
function _buildLP1Calculations(slide, isMarkingStation) {
  const PAGE_TOP = MARGIN;
  const PAGE_BOT = SLIDE_H - MARGIN;

  const lblX     = SLIDE_W - LL_W - MARGIN;
  const contentW = lblX - GUTTER - MARGIN;

  let hdrY = PAGE_TOP;
  slide.addText(
    isMarkingStation ? `Marking Station — ${LP1_DATA.title || "Calculations"}`
                     : (LP1_DATA.title || "Calculations"),
    { x: MARGIN, y: hdrY, w: contentW, h: 0.28,
      fontSize: 13, fontFace: FONT_M, bold: true,
      color: isMarkingStation ? GREEN : BLACK, margin: 0 }
  );
  hdrY += 0.30;
  if (!isMarkingStation && LP1_DATA.instruction) {
    slide.addText(LP1_DATA.instruction, {
      x: MARGIN, y: hdrY, w: contentW, h: 0.18,
      fontSize: 9, fontFace: FONT_C, color: "555555", margin: 0
    });
    hdrY += 0.20;
  }

  const questions = LP1_DATA.questions;
  const nQ        = questions.length;
  const nCols     = nQ <= 2 ? 1 : 2;
  const qColW     = contentW / nCols;
  const nRows     = Math.ceil(nQ / nCols);
  const usable    = PAGE_BOT - hdrY;
  const TARGET    = 10;
  const slotH     = usable / TARGET;
  const Q_ROW_H   = slotH / (nRows + 0.6);
  const fontSize  = Math.min(14, Math.max(10, Math.floor(Q_ROW_H * 58)));

  for (let rep = 0; rep < TARGET; rep++) {
    const stripTop = hdrY + rep * slotH;
    if (rep > 0) _cutStrip(slide, MARGIN, stripTop - 0.04, contentW);
    questions.forEach((q, i) => {
      const col = i % nCols;
      const row = Math.floor(i / nCols);
      const qx  = MARGIN + col * qColW;
      const qy  = stripTop + row * Q_ROW_H + (slotH - nRows * Q_ROW_H) / 2;
      slide.addText(_calcText(i + 1, q.q), {
        x: qx, y: qy, w: qColW - 0.08, h: Q_ROW_H,
        fontSize, fontFace: FONT_M, bold: true,
        color: isMarkingStation ? BLACK : "1F4E79",
        valign: "middle", margin: 0
      });
      if (isMarkingStation && q.answer) {
        slide.addText(q.answer, {
          x: qx + qColW * 0.55, y: qy, w: qColW * 0.4, h: Q_ROW_H,
          fontSize, fontFace: FONT_C, bold: true, color: GREEN,
          valign: "middle", margin: 0
        });
      }
    });
  }

  if (!isMarkingStation && LP1_DATA.goingFurther) {
    // Going further as full-width footer (no label column)
    const gfY = PAGE_BOT - 0.72;
    slide.addText("Going further:  " + LP1_DATA.goingFurther, {
      x: MARGIN, y: gfY, w: SLIDE_W - 2 * MARGIN, h: 0.65,
      fontSize: 9, fontFace: FONT_C, color: BLACK,
      fill: { color: "F2E6F9" }, line: { color: "7030A0", width: 0.75 },
      margin: 5, valign: "top"
    });
  }
}
// Layout: [Q1×reps] [Q2×reps] [Q3×reps] — identical strips grouped so they cut into sets.
// Estimate height for a text box in the right column based on content length
function estimateRightColH(text, labelH, fontSizePt) {
  // Approximate characters per line in the right column (LL_W ~1.022" at given pt size)
  const charsPerLine = Math.round(LL_W * 72 / (fontSizePt * 0.70));  // realistic for small fonts in narrow column
  const lines = Math.ceil(text.length / Math.max(charsPerLine, 8));
  const lineH = fontSizePt / 72 * 1.35;  // inches
  return (labelH || 0) + lines * lineH + 0.16;  // + internal padding
}

// ── COMPACT WORD PROBLEM LP ───────────────────────────────────────────────────
// Used when pupils record in books — no working space, pack as tight as possible.
// repsPerPage is calculated dynamically: measure content height, fit as many as possible.
// Exact measurements from Innes's reference (EXAMPLE_LPs.pptx slide 2).
function _buildCompactWithData(slide, isMarkingStation, data) {
  const Q_X     = 0.23;
  const Q_W     = 4.363;
  const RC_X    = 4.894;
  const RC_W    = 2.337;
  const RC_H    = 0.81;
  const TITLE_H = 0.28;
  const CUT_GAP = 0.20;
  const FS      = 10;

  const questions = data.questions;
  const nQ       = questions.length;
  const hasGF    = !isMarkingStation && !!(data.goingFurther || '').trim();
  const isLP2Mode     = !hasGF;
  const INSTR_IN_STRIP = !isLP2Mode && !isMarkingStation && !!data.instruction;
  const INSTR_H   = INSTR_IN_STRIP ? 0.18 : 0;
  const INSTR_GAP = INSTR_IN_STRIP ? 0.14 : 0.10;
  const Q_GAP     = isLP2Mode ? 0.02 : 0.10;
  const Q_END     = 0.08;

  function estimateQH(text) {
    const charsPerLine = Math.round(Q_W * 72 / (FS * 0.58));
    const fullText = 'Q?)   ' + text;
    const lines = Math.max(1, Math.ceil(fullText.length / charsPerLine));
    return lines * (FS / 72 * 1.25) + 0.04;
  }

  const qHeights    = questions.map(function(q) { return estimateQH(q.q); });
  const hdrH        = TITLE_H + (INSTR_H > 0 ? INSTR_H + 0.04 : 0) + INSTR_GAP;
  const qTotalH     = qHeights.reduce(function(s, h, i) { return s + h + (i < nQ-1 ? Q_GAP : Q_END); }, 0);
  const leftH       = hdrH + qTotalH;
  const rightH      = RC_H + 0.10;
  const repH        = Math.max(leftH, rightH) + CUT_GAP;
  const PAGE_TOP    = MARGIN;
  const PAGE_BOT    = SLIDE_H - MARGIN;
  const usable      = PAGE_BOT - PAGE_TOP;
  const repsPerPage = isMarkingStation ? 1 : Math.max(1, Math.floor(usable / repH));

  const repFrac = (PAGE_TOP + repH - CUT_GAP / 2) / SLIDE_H;
  slide.addNotes('INJECT_REPS:' + repsPerPage + '\nINJECT_REP_FRAC:' + repFrac.toFixed(4));

  for (let rep = 0; rep < repsPerPage; rep++) {
    const repTop     = PAGE_TOP + rep * repH;
    const contentTop = repTop + CUT_GAP / 2;

    if (rep > 0) _cutStrip(slide, Q_X, repTop, SLIDE_W - 2 * Q_X);

    let y = contentTop;

    slide.addText(
      isMarkingStation ? ('Marking Station \u2014 ' + (data.title || 'Problems')) : (data.title || 'Problems'),
      { x: Q_X, y: y, w: Q_W, h: TITLE_H, fontSize: 13, fontFace: FONT_M, bold: true,
        color: isMarkingStation ? GREEN : BLACK, margin: 0 }
    );
    y += TITLE_H;

    if (INSTR_IN_STRIP) {
      slide.addText(data.instruction, {
        x: Q_X, y: y, w: Q_W, h: INSTR_H,
        fontSize: 9, fontFace: FONT_C, color: '555555', margin: 0
      });
      y += INSTR_H + 0.04;
    }
    y += INSTR_GAP;

    for (let qi = 0; qi < nQ; qi++) {
      const q  = questions[qi];
      const qH = qHeights[qi];

      slide.addText('Q' + (qi + 1) + ')   ' + q.q, {
        x: Q_X, y: y, w: Q_W, h: qH, fontSize: FS, fontFace: FONT_C,
        color: isMarkingStation ? BLACK : '1F4E79',
        valign: 'top', margin: 0, wrap: true
      });

      if (isMarkingStation && q.answer) {
        slide.addText(q.answer, {
          x: Q_X, y: y + qH + 0.02, w: Q_W, h: 0.18,
          fontSize: 9, fontFace: FONT_C, bold: true, color: GREEN,
          valign: 'top', margin: 0, wrap: true
        });
        y += qH + 0.22 + (qi < nQ - 1 ? Q_GAP : Q_END);
      } else {
        y += qH + (qi < nQ - 1 ? Q_GAP : Q_END);
      }
    }

    if (!isMarkingStation) {
      if (hasGF) {
        slide.addText('Going further: ' + data.goingFurther, {
          x: RC_X, y: contentTop + 0.05, w: RC_W, h: RC_H,
          fontSize: 8, fontFace: FONT_C, color: BLACK,
          fill: { color: 'F2E6F9' }, line: { color: '7030A0', width: 0.75 },
          margin: 4, valign: 'top'
        });
      } else if (data.instruction) {
        slide.addText(data.instruction, {
          x: RC_X, y: contentTop + 0.05, w: RC_W, h: RC_H,
          fontSize: 8, fontFace: FONT_C, color: '555555',
          fill: { color: 'FFFFFF' }, line: { color: 'AAAAAA', width: 0.75 },
          margin: 4, valign: 'top'
        });
      }
    }
  }
}

